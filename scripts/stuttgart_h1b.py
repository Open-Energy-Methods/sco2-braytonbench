"""Stuttgart H1b: source-defined Bishop/Jackson wall-property HTC evaluation.

Two EPISTEMIC CLASSES are deliberately separate:
 - wall_conditioned: measured Tw supplied to correlation (diagnostic
   interpolation using response-associated information).
 - flux_inverted: heat flux and inlet-anchored bulk state are input;
   Tw is solved from q'' = HTC(Tw)*(Tw-Tb) with measured wall Tw hidden.

Bishop / Jackson-Hall do not resolve angular buoyancy. Richardson number
is a separately calculated *indicator*, not a new HTC adjustment.

Source data from Theologou et al. (2022) DOI 10.17632/4mvk4nxrkz.1,
CC BY 4.0. Baseline data and split are generated by stuttgart_h1.py.
"""
from __future__ import annotations
import argparse
from collections import Counter, defaultdict
import csv
import json
import math
from pathlib import Path
from statistics import mean, median

from sco2_braytonbench.stuttgart_correlations import (
    CorrelationDomainError,wall_property_nusselt,
    richardson_density_wall,flux_driven_wall_solution,
)

def read_csv(path:Path)->list[dict]:
    with path.open(encoding="utf-8",newline="") as f:
        return list(csv.DictReader(f))

def pct_error(pred,observed):
    return 100*(pred-observed)/observed

def quantile(a,q):
    if not a:return None
    a=sorted(a)
    k=(len(a)-1)*q
    lo=int(k);hi=min(len(a)-1,lo+1)
    return a[lo]+(a[hi]-a[lo])*(k-lo)

def metrics(rows:list[dict])->dict:
    if not rows:
        return dict(n=0,mape_pct=None,mean_bias_pct=None,
                    p90_ape_pct=None,mean_run_mape_pct=None,
                    mean_nominal_family_mape_pct=None)
    byrun=defaultdict(list)
    byfamily=defaultdict(list)
    for r in rows:
        ape=abs(r["relative_residual_pct"])
        byrun[r["experiment_id"]].append(ape)
        byfamily[r["nominal_family"]].append(ape)
    es=[r["relative_residual_pct"] for r in rows]
    apes=[abs(x) for x in es]
    return dict(n=len(rows),n_runs=len(byrun),
        mape_pct=mean(apes),
        mean_bias_pct=mean(es),
        median_ape_pct=median(apes),
        p90_ape_pct=quantile(apes,.9),
        rmspe_pct=math.sqrt(mean([x*x for x in es])),
        mean_run_mape_pct=mean([mean(v) for v in byrun.values()]),
        mean_nominal_family_mape_pct=mean([mean(v) for v in byfamily.values()]),
        within_reported_1sigma_fraction_descriptive_only=(
            mean([float(abs(r["relative_residual_pct"])<=r["reported_htc_sigma_pct"])
                 for r in rows if r["reported_htc_sigma_pct"] is not None]) ),
        n_nominal_families=len(byfamily))

def pseudocritical_temperature(props,pressure_pa:float)->float:
    """Maximum cp(T,p) search at fixed pressure, NOT fixed Tcritical.

    Limited to 304.2-360 K for these measured near-critical states.
    For broader fluid states, implement an EOS-wide bounded search.
    """
    if not math.isfinite(pressure_pa) or pressure_pa<=7.3773e6:
        raise CorrelationDomainError("pseudocritical T requires p above CO2 critical")
    lo,hi=304.2,360.
    phi=(math.sqrt(5)-1)/2
    a=hi-phi*(hi-lo);b=lo+phi*(hi-lo)
    def cp(t):
        return props("Cpmass","P",pressure_pa,"T",t,"HEOS::CO2")
    ca,cb=cp(a),cp(b)
    for _ in range(43):
        if ca<cb:
            lo=a;a=b;ca=cb;b=lo+phi*(hi-lo);cb=cp(b)
        else:
            hi=b;b=a;cb=ca;a=hi-phi*(hi-lo);ca=cp(a)
    t=(lo+hi)/2
    if t<=304.21 or t>=359.99:
        raise CorrelationDomainError("pseudocritical cp peak not bracketed")
    return t

def evaluate(
    index_path:Path,baseline_points_path:Path,baseline_report_path:Path,
    out_dir:Path,props,
    *,min_coverage_per_mode:float=.8,
)->dict:
    meta={r["experiment_id"]:r for r in read_csv(index_path)}
    if len(meta)!=54:
        raise ValueError("Stuttgart H1b requires exactly original 54 source experiment IDs")
    base=json.loads(baseline_report_path.read_text(encoding="utf-8"))
    if base["split"]["salt"]!="BraytonBench-STU-H1-v1-2026-11-05" or not base["split"]["no_parameter_fitting"]:
        raise ValueError("original held-out nominal family partition cannot change")
    families=set(base["split"]["held_out_families"])
    if len(families)!=4:raise ValueError("expected four predeclared nominal holdouts")
    first=[r for r in read_csv(baseline_points_path)
           if r["model"]=="gnielinski_smooth_bulk"]
    if len(first)!=2318:
        raise ValueError("H1b expects H1a 2318 eligible baseline stations")
    names=("bishop_wall_conditioned","jackson_wall_conditioned",
           "bishop_flux_inverted","jackson_flux_inverted")
    out=[]
    exclusions=Counter()
    pc_cache={}

    for r in first:
        experiment=r["experiment_id"]
        if experiment=="4MM_HM_77.5_10_20_90_A":
            raise ValueError("STU-001 quarantine must not be bypassed")
        raw=meta[experiment]
        p=float(r["pressure_pa_assumed_constant"])
        tb=float(r["bulk_temperature_k_from_inlet_anchored_delta_h"])
        tw_measured=float(r["measured_wall_temperature_k_diagnostic_only"])
        d=float(r["diameter_mm"])/1000.
        x_over_d=float(r["x_over_d"])
        re=float(r["reynolds"])
        pr=float(r["prandtl"])
        mdot=float(raw["mass_flow_kg_s"])
        q=float(raw["heat_flux_kw_m2"])*1e3
        observed=float(r["measured_reduced_htc_w_m2_k"])
        try:
            mu=props("VISCOSITY","P",p,"T",tb,"HEOS::CO2")
            conductivity=props("CONDUCTIVITY","P",p,"T",tb,"HEOS::CO2")
            cp=props("Cpmass","P",p,"T",tb,"HEOS::CO2")
            rho=props("Dmass","P",p,"T",tb,"HEOS::CO2")
            if p not in pc_cache:
                pc_cache[p]=pseudocritical_temperature(props,p)
            tpc=pc_cache[p]
            if not all(math.isfinite(v) and v>0 for v in (mu,conductivity,cp,rho,q,observed,tw_measured-tb)):
                raise CorrelationDomainError("invalid comparison fluid or measured wall state")
        except (CorrelationDomainError,ValueError,RuntimeError,OverflowError) as exc:
            exclusions[("all",str(exc)[:90])]+=4
            continue

        mass_flux=4*mdot/(math.pi*d*d)
        try:
            ri_measured=richardson_density_wall(
                rho,props("Dmass","P",p,"T",tw_measured,"HEOS::CO2"),d,mass_flux)
        except (CorrelationDomainError,ValueError,RuntimeError,OverflowError):
            ri_measured=None
        for name in names:
            # Bishop's original supercritical-water fit was for x/D 30-565.
            # This is a physical extrapolation to horizontal sCO2 even
            # within this geometric range, so never label it validated.
            if name.startswith("bishop_") and not 30<=x_over_d<=565:
                exclusions[(name,"outside_Bishop_original_x_over_D_range")]+=1
                continue
            try:
                if name.endswith("_conditioned"):
                    tw=tw_measured
                    nu=wall_property_nusselt(
                        name,re,float(r["prandtl"]),rho,mu,conductivity,cp,
                        tb,tw,p,x_over_d,props,tpc)
                    pred=nu*conductivity/d
                    n_iters=0
                else:
                    tw,pred,n_iters=flux_driven_wall_solution(
                        name,q,d,re,float(r["prandtl"]),rho,
                        mu,conductivity,cp,tb,p,x_over_d,tpc,props,
                        tolerance_k=.08,max_iterations=19)
                if not math.isfinite(pred) or pred<=0:
                    raise CorrelationDomainError("nonpositive predicted HTC")
                rho_pred=props("Dmass","P",p,"T",tw,"HEOS::CO2")
                ri_prediction=richardson_density_wall(rho,rho_pred,d,mass_flux)
            except (CorrelationDomainError,ValueError,RuntimeError,OverflowError) as exc:
                exclusions[(name,type(exc).__name__+":"+str(exc)[:70])]+=1
                continue
            rel=pct_error(pred,observed)
            sigma=float(r["reported_htc_sigma_pct"]) if r["reported_htc_sigma_pct"] else None
            out.append(dict(
                experiment_id=experiment,nominal_family=r["nominal_family"],
                split=r["split"],orientation=r["orientation"],
                diameter_mm=float(r["diameter_mm"]),
                x_over_d=x_over_d,axial_position_m=float(r["axial_position_m"]),
                model=name,mode=("measured_wall_diagnostic" if name.endswith("_conditioned")
                                 else "a_priori_wall_inverse_from_reported_heat_flux"),
                bulk_temperature_k=tb,measured_wall_temperature_k_diagnostic_only=tw_measured,
                input_heat_flux_w_m2=q,
                calculated_or_conditioned_wall_temperature_k=tw,
                pseudocritical_temperature_k=tpc,
                measured_derived_htc_w_m2_k=observed,
                predicted_htc_w_m2_k=pred,
                relative_residual_pct=rel,
                reported_htc_sigma_pct=sigma,
                richardson_from_measured_wall_diagnostic=ri_measured,
                richardson_from_predicted_or_conditioned_wall=ri_prediction,
                buoyancy_flag_threshold_1e_minus3=bool(ri_prediction>0.001),
                residual_absolute_as_pct_source_sigma=(abs(rel)/sigma if sigma else None),
                n_wall_inverse_iterations=n_iters,
                original_baseline_gnielinski_htc_w_m2_k=float(r["predicted_htc_w_m2_k"]),
                original_baseline_gnielinski_relative_residual_pct=float(r["relative_residual_pct"]),
            ))

    if not out:raise ValueError("H1b no predictions")
    modeled=Counter(r["model"] for r in out)
    n_base=len(first)
    if any(modeled[name]/n_base<min_coverage_per_mode for name in names):
        raise ValueError("H1b coverage below predeclared minimum; inspect physics errors "+repr(modeled))

    table={}
    for name in names:
        rows=[r for r in out if r["model"]==name]
        by_or={o:metrics([r for r in rows if r["orientation"]==o])
               for o in ("HB","HM","HT")}
        table[name]=dict(
            overall=metrics(rows),
            held_out=metrics([r for r in rows if r["split"]=="held_out"]),
            development=metrics([r for r in rows if r["split"]=="development"]),
            orientation=by_or,
            diameter_mm={str(d):metrics([r for r in rows if r["diameter_mm"]==d])
                         for d in (4.,8.)},
            buoyancy_flagged_fraction=mean([float(r["buoyancy_flag_threshold_1e_minus3"]) for r in rows]),
            **({"same_stations_gnielinski":metrics([
                dict(r,relative_residual_pct=r["original_baseline_gnielinski_relative_residual_pct"])
                for r in rows])}),
        )
    out_dir.mkdir(parents=True,exist_ok=True)
    with (out_dir/"h1b_pointwise.csv").open("w",encoding="utf-8",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=list(out[0]))
        writer.writeheader();writer.writerows(out)
    report={
        "source":"Theologou et al. (2022), DOI 10.17632/4mvk4nxrkz.1, CC BY 4.0",
        "study":"H1b Bishop and Jackson-Hall wall-conditioned and flux-driven comparisons",
        "source_paper_htc_is_experimentally_derived":True,
        "original_split":base["split"],
        "source_quarantine_preserved":"4MM_HM_77.5_10_20_90_A",
        "reference_baseline_total_stations":n_base,
        "source_specific_model_info":{
            "bishop":"Theologou Eq.15; original Bishop fit upward supercritical water not horizontal CO2; x/D 30-565 original domain",
            "jackson":"Jackson-Hall 1979 temperature-case variable-property correction; original thermohydraulic applicability to Stuttgart not established",
            "wall_conditioned":"MEASURED wall temperature is model input; cannot be called a-priori prediction",
            "flux_inverted":"measured applied heat flux and bulk enthalpy increment input; wall temperature solved, not measured input",
            "buoyancy":"Richardson Gr/Re^2 from wall/bulk density, diagnostic flag >0.001, no buoyancy correction to Nu",
        },
        "models":table,
        "domain_exclusions":[{"model":k[0],"reason":k[1],"n":n}
                             for k,n in sorted(exclusions.items())],
        "uncertainty_caveats":[
          "Source HTC is calculated from measured heat flux and wall/bulk temperatures; error terms are correlated",
          "Wall-conditioned evaluation leaks measured response-associated wall temperature by design",
          "Flux-driven inversion uses reported experiment heat flux; it is NOT an industrial uncontrolled-state model",
          "Pseudocritical cp maximized over 304.2-360 K at measured inlet P; axial P assumed constant",
          "No cross-validated fitted parameters; same held-out groups as H1a; no nominal group reassignment",
          "Bishop original supercritical-water flow domain is extrapolated to horizontal CO2",
          "Jackson-Hall contains property correction but no explicit top/bottom buoyancy transport",
          "Reported 1-sigma comparison is descriptive only; no input covariance, 95% CI or model-form uncertainty",
          "Do not apply tested single-pipe HTC as PCHE or complete cycle UA",
        ],
        "gate":"H1b_implementation_comparison_only_accuracy_must_be_reviewed",
    }
    (out_dir/"h1b_report.json").write_text(json.dumps(report,indent=2,allow_nan=False)+"\n",encoding="utf-8")
    return report

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--data-dir",type=Path,default=Path("data/validation/stuttgart"))
    ap.add_argument("--baseline-dir",type=Path,default=Path("evidence/generated/stuttgart_h1"))
    ap.add_argument("--out",type=Path,default=Path("evidence/generated/stuttgart_h1b"))
    args=ap.parse_args()
    from CoolProp.CoolProp import PropsSI
    import CoolProp
    result=evaluate(args.data_dir/"experiment_index.csv",
        args.baseline_dir/"local_predictions.csv",
        args.baseline_dir/"report.json",
        args.out,PropsSI)
    result["CoolProp_version"]=CoolProp.__version__
    (args.out/"h1b_report.json").write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8")
    print(json.dumps({
        "CoolProp":CoolProp.__version__,
        "models":{k:{
            "overall":v["overall"],
            "held_out":v["held_out"],
            "HB":v["orientation"]["HB"]["mape_pct"],
            "HT":v["orientation"]["HT"]["mape_pct"],
            "same_stations_gnielinski_M­APE":v["same_stations_gnielinski"]["mape_pct"],
            "buoyancy_flagged_fraction":v["buoyancy_flagged_fraction"],
        } for k,v in result["models"].items()},
        "domain_exclusions":result["domain_exclusions"]
    },indent=2))
if __name__=="__main__":
    main()
