"""Deterministic synthetic TES trajectory dataset with whole-run partitions.

All observations are generated by this repository's idealized, constant
property packed-bed finite-volume solver. No actual sensors, external
plant measurements, CIC energiGUNE facility data, or input PDFs are
present. Heldout runs have separate LHS seeds and disjoint run IDs.

This generator uses only Python stdlib, keeping the model's base install
minimal. The OOD sample intentionally exits the TRAIN design envelope;
it is NOT evidence that model extrapolation is trustworthy.

The 512-run full dataset is a resource-aware, N=8 numerical study, not
a surrogate for N=128 Schumann-convergence evidence. Higher-N and
full timestep/spatial sensitivity remain additional requirements.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path
import random
from collections import Counter

from sco2_braytonbench.thermal_storage import (
    PackedBedSpec, PackedBedState, solid_soc,
    stored_energy_j, step_packed_bed
)

SEEDS = {"train": 1211, "validation": 2213, "test": 3217, "ood": 4219}
COUNTS_FULL = {"train": 256, "validation": 64, "test": 128, "ood": 64}
COUNTS_SMOKE = {"train": 4, "validation": 2, "test": 2, "ood": 2}
SAMPLE_TIMES = 8
COLD_MIN_K, COLD_MAX_K = 340.0, 430.0
HOT_MIN_K, HOT_MAX_K = 500.0, 800.0
FLOW_MIN_KG_S, FLOW_MAX_KG_S = 0.01, 0.10
HV_MIN, HV_MAX = 250.0, 1000.0
DURATION_TURNOVER_MIN, DURATION_TURNOVER_MAX = 0.25, 4.0


def _lhs(n: int, dim: int, seed: int) -> list[tuple[float, ...]]:
    """Stratified marginals; each split is independently permuted."""
    rng = random.Random(seed)
    columns = []
    for _ in range(dim):
        x = [(i + rng.random()) / n for i in range(n)]
        rng.shuffle(x)
        columns.append(x)
    return [tuple(col[i] for col in columns) for i in range(n)]


def _interpolate(unit: float, low: float, high: float) -> float:
    return low + (high - low) * unit


def _parameters(split: str, point: tuple[float, ...]) -> dict[str, float]:
    if split == "ood":
        # Out-of-design-range flow or inlet temperature, never merely
        # a different in-domain LHS seed.
        cold = _interpolate(point[0], COLD_MIN_K, COLD_MAX_K)
        hot = _interpolate(point[1], 810.0, 855.0)
        flow = _interpolate(point[2], .105, .15)
    else:
        cold = _interpolate(point[0], COLD_MIN_K, COLD_MAX_K)
        hot = _interpolate(point[1], HOT_MIN_K, HOT_MAX_K)
        # Logarithmic mass flow samples over exactly one decade.
        flow = FLOW_MIN_KG_S * (
            FLOW_MAX_KG_S / FLOW_MIN_KG_S
        ) ** point[2]
    return {
        "initial_k": cold,
        "hot_inlet_k": hot,
        "flow_kg_s": flow,
        "hv_w_m3_k": _interpolate(point[3], HV_MIN, HV_MAX),
        "charge_turnovers": _interpolate(
            point[4], DURATION_TURNOVER_MIN, DURATION_TURNOVER_MAX
        ),
        "discharge_turnovers": _interpolate(
            point[5], DURATION_TURNOVER_MIN, DURATION_TURNOVER_MAX
        ),
    }


def spec(hv_w_m3_k: float, *, n_cells: int = 8) -> PackedBedSpec:
    """Deliberately small synthetic bed; no material/source calibration."""
    return PackedBedSpec(
        length_m=1.0,
        area_m2=0.1,
        porosity=0.5,
        fluid_density_kg_m3=5.0,
        fluid_cp_j_kg_k=1000.0,
        solid_density_kg_m3=1000.0,
        solid_cp_j_kg_k=700.0,
        interphase_hv_w_m3_k=hv_w_m3_k,
        n_cells=n_cells
    )


def _write_table(filename: Path, rows: list[dict]) -> str:
    if not rows:
        raise ValueError("empty generated trajectory table")
    with filename.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return hashlib.sha256(filename.read_bytes()).hexdigest()


def _generate_one(
    split: str,
    run_id: str,
    point: tuple[float, ...],
    *,
    n_cells: int,
) -> tuple[list[dict], dict]:
    param = _parameters(split, point)
    s = spec(param["hv_w_m3_k"], n_cells=n_cells)
    initial = PackedBedState.uniform(s, param["initial_k"], param["initial_k"])
    total_capacity = (s.total_fluid_capacity_j_k + s.total_solid_capacity_j_k)
    turnover_s = total_capacity / (
        param["flow_kg_s"] * s.fluid_cp_j_kg_k
    )
    if not math.isfinite(turnover_s) or turnover_s <= 0:
        raise ValueError("invalid thermal turnover time")
    durations = (
        turnover_s * param["charge_turnovers"],
        turnover_s * param["discharge_turnovers"],
    )
    phase_configs = (
        ("charge", param["hot_inlet_k"], param["flow_kg_s"]),
        ("discharge", param["initial_k"], -param["flow_kg_s"]),
    )
    current = initial
    time_s = 0.0
    phase_rows = []
    max_energy_residual_j = 0.0
    for phase_index, (phase, inlet_k, signed_mdot) in enumerate(phase_configs):
        duration = durations[phase_index]
        for sample in range(1, SAMPLE_TIMES + 1):
            duration_part_s = duration / SAMPLE_TIMES
            step = step_packed_bed(
                s, current,
                inlet_k=inlet_k,
                mdot_kg_s=signed_mdot,
                duration_s=duration_part_s,
                max_substeps=250000
            )
            current = step.state
            time_s += duration_part_s
            max_energy_residual_j = max(
                max_energy_residual_j, abs(step.conservation_residual_j)
            )
            soc = solid_soc(
                s, current, cold_k=param["initial_k"],
                hot_k=param["hot_inlet_k"]
            )
            # Feature fields are known before numerical prediction; target
            # fields are never used as model inputs during surrogate fits.
            phase_rows.append({
                "split": split,
                "run_id": run_id,
                "phase": phase,
                "phase_fraction": sample / SAMPLE_TIMES,
                "elapsed_s": time_s,
                "phase_duration_s": duration,
                "initial_k": param["initial_k"],
                "hot_inlet_k": param["hot_inlet_k"],
                "inlet_k": inlet_k,
                "flow_kg_s": param["flow_kg_s"],
                "signed_flow_kg_s": signed_mdot,
                "hv_w_m3_k": param["hv_w_m3_k"],
                "charge_turnovers": param["charge_turnovers"],
                "discharge_turnovers": param["discharge_turnovers"],
                "thermal_turnover_s": turnover_s,
                "bed_cells": n_cells,
                "fluid_outlet_k": step.outlet_k,
                "solid_soc": soc,
                "boundary_energy_j": step.energy_boundary_j,
                "first_law_residual_j": step.conservation_residual_j,
                "courant": step.courant_per_substep,
                "exchange_fluid": step.exchange_fluid_per_substep,
                "exchange_solid": step.exchange_solid_per_substep,
            })
    return phase_rows, {
        "run_id": run_id, "split": split, **param,
        "total_time_s": time_s,
        "max_abs_energy_residual_j": max_energy_residual_j,
        "terminal_solid_soc": phase_rows[-1]["solid_soc"],
        "temperature_outlet_min_k": min(
            x["fluid_outlet_k"] for x in phase_rows
        ),
        "temperature_outlet_max_k": max(
            x["fluid_outlet_k"] for x in phase_rows
        )
    }


def generate_dataset(
    outdir: Path,
    *,
    counts: dict[str, int] | None = None,
    n_cells: int = 8,
) -> dict:
    """Generate disjoint split files, run manifest and integrity checks."""
    counts = dict(COUNTS_FULL if counts is None else counts)
    if counts.keys() != SEEDS.keys() or any(
        type(n) is not int or n < 1 for n in counts.values()
    ):
        raise ValueError("each declared dataset split needs a positive count")
    if type(n_cells) is not int or n_cells < 1:
        raise ValueError("n_cells must be positive integer")
    outdir.mkdir(parents=True, exist_ok=True)
    files = {}
    all_ids = []
    diagnostics = {}
    for split in SEEDS:
        input_points = _lhs(counts[split], 6, SEEDS[split])
        rows = []
        runs = []
        for i, point in enumerate(input_points):
            run_id = f"{split.upper()}-{i:05}"
            samples, summary = _generate_one(
                split, run_id, point, n_cells=n_cells
            )
            rows.extend(samples)
            runs.append(summary)
            all_ids.append(run_id)
        file = outdir / f"tes_{split}_trajectories.csv"
        files[file.name] = _write_table(file, rows)
        file = outdir / f"tes_{split}_run_index.csv"
        files[file.name] = _write_table(file, runs)
        assert len(rows) == counts[split] * SAMPLE_TIMES * 2
        diagnostics[split] = {
            "runs": len(runs),
            "rows": len(rows),
            "max_abs_energy_residual_j": max(
                x["max_abs_energy_residual_j"] for x in runs
            ),
            "soc_min": min(row["solid_soc"] for row in rows),
            "soc_max": max(row["solid_soc"] for row in rows),
            "outlet_min_k": min(row["fluid_outlet_k"] for row in rows),
            "outlet_max_k": max(row["fluid_outlet_k"] for row in rows)
        }
    if len(set(all_ids)) != len(all_ids):
        raise AssertionError("run ID data leakage between splits")
    manifest = {
        "schema": "tes-synthetic-trajectories-v0.6",
        "evidence_class": "entirely-synthetic-two-temperature-finite-volume",
        "excluded_claims": [
            "CIC energiGUNE storage measurements",
            "CARBOSOLA measurement",
            "full CFD",
            "PCM phase-change",
            "mechanical liquid-piston",
            "experimentally validated ROM"
        ],
        "seeds": dict(SEEDS),
        "counts": counts,
        "samples_per_run": SAMPLE_TIMES * 2,
        "n_cells": n_cells,
        "train_envelope": {
            "initial_k": [COLD_MIN_K, COLD_MAX_K],
            "hot_inlet_k": [HOT_MIN_K, HOT_MAX_K],
            "flow_kg_s": [FLOW_MIN_KG_S, FLOW_MAX_KG_S],
            "hv_w_m3_k": [HV_MIN, HV_MAX],
            "charge_and_discharge_turnovers": [
                DURATION_TURNOVER_MIN, DURATION_TURNOVER_MAX
            ]
        },
        "ood_outside_train_envelope": {
            "hot_inlet_k": [810, 855],
            "flow_kg_s": [.105, .15]
        },
        "model_geometry": {
            "length_m": 1.,
            "bulk_area_m2": .1,
            "porosity": .5,
            "fluid_rho_kg_m3": 5.,
            "fluid_cp_j_kg_k": 1000.,
            "solid_rho_kg_m3": 1000.,
            "solid_cp_j_kg_k": 700.
        },
        "sample_semantics": (
            "8 successive cell-solver outputs during charge, then 8 "
            "during reverse-flow discharge; each row is a correlated "
            "time sample, while split assignment is by complete run"
        ),
        "split_integrity": {
            "distinct_run_ids": len(all_ids),
            "duplicate_run_ids": len(all_ids) - len(set(all_ids)),
            "separately_seeded_lhs": True,
            "time_row_random_split": False,
            "test_sealed_from_training": (
                "Protocol-separated whole-run test partition. Files are "
                "public and cannot be cryptographically hidden from readers."
            )
        },
        "diagnostics": diagnostics,
        "sha256": files,
    }
    path = outdir / "tes_dataset_manifest.json"
    path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8"
    )
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out", type=Path,
        default=Path("evidence/generated/tes_v06"),
        help="Destination for per-split CSVs and manifest"
    )
    parser.add_argument(
        "--smoke", action="store_true",
        help="Generate a small complete-split CI test, not 512 runs"
    )
    args = parser.parse_args()
    m = generate_dataset(
        args.out,
        counts=COUNTS_SMOKE if args.smoke else COUNTS_FULL
    )
    print(json.dumps({
        "counts": m["counts"],
        "diagnostics": m["diagnostics"],
        "sha256": m["sha256"]
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
